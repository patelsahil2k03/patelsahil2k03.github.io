#!/usr/bin/env python3
"""Builds docs/AGENT_CARD.md from the blocks of nextprompt.md marked  <!-- card:start LABEL -->  ...  <!-- card:end -->.

The wording stays owned by nextprompt.md: the card copies the marked blocks verbatim, so a rule is edited in one place and the card
follows. The SessionStart hook (session_context.py) injects the card at every start, resume, clear and compaction.

  python3 tools/agent-guard/build_card.py           write docs/AGENT_CARD.md
  python3 tools/agent-guard/build_card.py --check   exit 1 if the card is out of date (a test runs this)
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "nextprompt.md"
CARD = ROOT / "docs" / "AGENT_CARD.md"
START = re.compile(r"^<!-- card:start (.+?) -->\s*$")
END = re.compile(r"^<!-- card:end -->\s*$")

HEADER = """# Agent card

**GENERATED from `nextprompt.md` by `tools/agent-guard/build_card.py`. Do not edit this file: edit the rule in `nextprompt.md`, then run the builder.**

These are the rules whose violation is expensive, copied word for word from the blocks of `nextprompt.md` marked `<!-- card:start -->`.
It is injected at every session start, resume, clear and compaction (`tools/agent-guard/session_context.py`). It is a reminder, not a
substitute: read the whole section named in a heading before the action it governs.
"""


def blocks(text):
    """Yield (label, body) for every marked block; raise on an unbalanced marker."""
    label, body = None, []
    for number, line in enumerate(text.split("\n"), 1):
        start = START.match(line)
        if start:
            if label is not None:
                raise ValueError(f"nextprompt.md:{number}: card:start inside an open block ({label})")
            label, body = start.group(1), []
        elif END.match(line):
            if label is None:
                raise ValueError(f"nextprompt.md:{number}: card:end without a start")
            yield label, "\n".join(body).strip("\n")
            label = None
        elif label is not None:
            body.append(line)
    if label is not None:
        raise ValueError(f"nextprompt.md: block '{label}' is never closed")


def build(source_text):
    parts = [HEADER.rstrip("\n")]
    for label, body in blocks(source_text):
        parts.append(f"## {label}\n\n{body}")
    return "\n\n".join(parts) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when docs/AGENT_CARD.md differs from what nextprompt.md produces")
    args = ap.parse_args(argv)
    want = build(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        have = CARD.read_text(encoding="utf-8") if CARD.is_file() else ""
        if have != want:
            print("docs/AGENT_CARD.md is out of date: run python3 tools/agent-guard/build_card.py", file=sys.stderr)
            return 1
        print("docs/AGENT_CARD.md is up to date")
        return 0
    CARD.write_text(want, encoding="utf-8")
    print(f"wrote {CARD.relative_to(ROOT)} ({len(want):,} bytes, {want.count(chr(10) + '## ')} blocks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
